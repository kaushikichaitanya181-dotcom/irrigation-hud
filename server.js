const express = require('express');
const path = require('path');
const app = express();
const PORT = process.env.PORT || 10000;

app.use(express.json());
app.use(express.static(path.join(__dirname, 'public')));

app.get('/', (req, res) => {
    res.sendFile(path.join(__dirname, 'public', 'index.html'));
});

app.post('/api/register', (req, res) => {
    const { username, password } = req.body;
    if (!username || !password) {
        return res.status(400).json({ success: false, message: "All authentication fields required." });
    }
    res.status(200).json({ success: true, message: `System Account "${username}" registered successfully.` });
});

app.listen(PORT, () => {
    console.log(`Smart Irrigation active on port ${PORT}`);
});
